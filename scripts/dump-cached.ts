// Evidence dump for the verification engine: for every formula cell of every wk1/wks fixture in
// the manifest, print its address, the cached double as 16 hex digits and its class, and for each
// reference or range in its decoded AST the kind of each cell there. Uses parseWk1 and decodeRpn
// only, so the evidence does not depend on the engine it is used to check.
// Run: bun scripts/dump-cached.ts [out.md]   (prints to stdout without an argument)
// With an argument, the text of out.md above the "## Generated dump" line is kept, so the
// hand-written findings in docs/verify-evidence.md survive a rerun.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import type { Expr } from "../src/formula/index.ts";
import { decodeRpn } from "../src/formula/index.ts";
import { a1, cellKey, cellsInRowMajorOrder, parseWk1, type Sheet } from "../src/parser/index.ts";

type Entry = { path: string; format: string; origin: string };
const manifest = JSON.parse(readFileSync("fixtures/manifest.json", "utf8")) as { fixtures: Entry[] };

const MARKER = "## Generated dump";

/**
 * The stored bit pattern of every NUMBER and FORMULA cell, read from the file bytes, because the
 * parser hands back a JS number and a runtime may replace a NaN payload with its own. Only the
 * record framing (opcode u16, length u16, body) and the cell header (format u8, col u16, row u16)
 * from steering/lotus-format.md are used; the double follows the header in both records.
 */
function rawBits(bytes: Uint8Array): Map<number, string> {
  const out = new Map<number, string>();
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  for (let pos = 0; pos + 4 <= bytes.length; ) {
    const opcode = view.getUint16(pos, true);
    const length = view.getUint16(pos + 2, true);
    const body = pos + 4;
    if ((opcode === 0x0e || opcode === 0x10) && length >= 13 && body + 13 <= bytes.length) {
      const key = cellKey(view.getUint16(body + 1, true), view.getUint16(body + 3, true));
      out.set(key, view.getBigUint64(body + 5, true).toString(16).padStart(16, "0"));
    }
    pos = body + length;
  }
  return out;
}

function cls(d: number): string {
  if (Number.isNaN(d)) return "NaN";
  if (d === Infinity) return "+Infinity";
  if (d === -Infinity) return "-Infinity";
  return "finite";
}

function kindAt(sheet: Sheet, col: number, row: number): string {
  const cell = sheet.cells.get(cellKey(col, row));
  if (!cell) return "empty";
  if (cell.kind === "number" && !Number.isFinite(cell.value)) return `number(${cls(cell.value)})`;
  return cell.kind;
}

/** Every ref and range in the AST, in written order. An explicit stack, no recursion. */
function refsOf(ast: Expr): Expr[] {
  const out: Expr[] = [];
  const stack: Expr[] = [ast];
  while (stack.length > 0) {
    const e = stack.pop()!;
    if (e.type === "ref" || e.type === "range") out.push(e);
    else if (e.type === "unary") stack.push(e.arg);
    else if (e.type === "paren") stack.push(e.inner);
    else if (e.type === "binary") stack.push(e.right, e.left);
    else if (e.type === "call") stack.push(...[...e.args].reverse());
  }
  return out;
}

function describeRef(sheet: Sheet, e: Expr): string {
  if (e.type === "ref") return `${a1(e.ref.col, e.ref.row)}=${kindAt(sheet, e.ref.col, e.ref.row)}`;
  if (e.type !== "range") return "";
  const [c0, c1] = [Math.min(e.from.col, e.to.col), Math.max(e.from.col, e.to.col)];
  const [r0, r1] = [Math.min(e.from.row, e.to.row), Math.max(e.from.row, e.to.row)];
  const kinds: string[] = [];
  for (let r = r0; r <= r1; r++) for (let c = c0; c <= c1; c++) kinds.push(`${a1(c, r)}=${kindAt(sheet, c, r)}`);
  return `${a1(c0, r0)}..${a1(c1, r1)}[${kinds.join(" ")}]`;
}

const lines: string[] = [
  MARKER,
  "",
  "Generated by `bun scripts/dump-cached.ts docs/verify-evidence.md`. Each line: address, cached double as 16 hex digits (the bit pattern as stored in the file, most significant first), its class, the decimal value, then the kind of every cell each reference or range in the decoded formula points at.",
  "",
];

for (const entry of manifest.fixtures.filter((e) => e.format === "wk1" || e.format === "wks")) {
  const bytes = new Uint8Array(readFileSync(entry.path));
  const { sheet } = parseWk1(bytes);
  const raw = rawBits(bytes);
  const bits = (col: number, row: number) => raw.get(cellKey(col, row)) ?? "????????????????";
  const cells = cellsInRowMajorOrder(sheet);
  const formulas = cells.filter((c) => c.kind === "formula");
  const oddInputs = cells.flatMap((c) => (c.kind === "number" && !Number.isFinite(c.value) ? [`${a1(c.col, c.row)} ${bits(c.col, c.row)} ${cls(c.value)}`] : []));
  lines.push(`### ${entry.path} (${entry.origin}, ${formulas.length} formulas)`, "");
  lines.push(`Number cells with a non-finite value: ${oddInputs.length === 0 ? "none" : oddInputs.join(", ")}.`, "");
  if (formulas.length === 0) continue;
  lines.push("```");
  for (const c of formulas) {
    if (c.kind !== "formula") continue;
    const decoded = decodeRpn(c.rpn, { col: c.col, row: c.row });
    const refs = decoded.ast === null ? "decode failed" : refsOf(decoded.ast).map((e) => describeRef(sheet, e)).join(" ");
    lines.push(`${a1(c.col, c.row).padEnd(6)} ${bits(c.col, c.row)} ${cls(c.cached).padEnd(9)} ${String(c.cached).padEnd(22)} ${refs}`);
  }
  lines.push("```", "");
}

const out = process.argv[2];
if (out) {
  const old = existsSync(out) ? readFileSync(out, "utf8") : "";
  const at = old.indexOf(MARKER);
  writeFileSync(out, (at >= 0 ? old.slice(0, at) : "") + lines.join("\n"));
} else {
  console.log(lines.join("\n"));
}
