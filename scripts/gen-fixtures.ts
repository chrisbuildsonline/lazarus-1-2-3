// Writes the synthetic WK1 fixtures, their LICENSE.txt and their manifest entries.
// No network, no clock, no randomness: two runs give byte-identical output.
// Usage: bun scripts/gen-fixtures.ts
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { SPECS } from "./lib/fixture-specs.ts";
import { writeWk1, type CellSpec } from "./lib/wk1-writer.ts";

export type Counts = { cells: number; formulas: number; labels: number; numbers: number };
export type ExpectedValue = { cell: string; kind: CellSpec["kind"] | "other"; cached: number | string };
export type ManifestEntry = {
  path: string;
  format: "wk1" | "wks" | "dbf";
  origin: "real" | "synthetic";
  sourceUrl: string | null;
  license: string;
  sha256: string;
  counts: Counts;
  expectedValues: ExpectedValue[];
};

const MANIFEST = "fixtures/manifest.json";
export const LICENSE_TEXT =`Source: generated by scripts/gen-fixtures.ts
Author: Lazarus 1-2-3 project
License: MIT
Redistribution: allowed
Notes: synthetic file built from scripts/lib/fixture-specs.ts. Do not edit by hand; rerun the generator.
`;

function a1(col: number, row: number): string {
  let name = "";
  for (let c = col + 1; c > 0; c = Math.floor((c - 1) / 26)) name = String.fromCharCode(65 + ((c - 1) % 26)) + name;
  return `${name}${row + 1}`;
}

function counts(cells: readonly CellSpec[]): Counts {
  const of = (k: CellSpec["kind"]) => cells.filter((c) => c.kind === k).length;
  return { cells: cells.length, formulas: of("formula"), labels: of("label"), numbers: of("integer") + of("number") };
}

function expectedValue(cells: readonly CellSpec[], address: string): ExpectedValue {
  const c = cells.find((x) => a1(x.col, x.row) === address);
  if (!c) throw new Error(`spec has no cell ${address}`);
  const cached = c.kind === "label" ? c.text : c.kind === "formula" ? c.cached : c.value;
  return { cell: address, kind: c.kind, cached };
}

export function buildAll(): { path: string; bytes: Uint8Array; manifestEntry: ManifestEntry }[] {
  return SPECS.map((spec) => {
    const path = `fixtures/${spec.name}/${spec.name}.wk1`;
    const bytes = writeWk1(spec.version, spec.cells);
    const manifestEntry: ManifestEntry = {
      path,
      format: "wk1",
      origin: "synthetic",
      sourceUrl: null,
      license: "MIT",
      sha256: createHash("sha256").update(bytes).digest("hex"),
      counts: counts(spec.cells),
      expectedValues: spec.expect.map((address) => expectedValue(spec.cells, address)),
    };
    return { path, bytes, manifestEntry };
  });
}

function main(): void {
  const built = buildAll();
  for (const { path, bytes } of built) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, bytes);
    writeFileSync(`${dirname(path)}/LICENSE.txt`, LICENSE_TEXT);
  }
  const old = JSON.parse(readFileSync(MANIFEST, "utf8")) as { fixtures: ManifestEntry[] };
  const fixtures = [...old.fixtures.filter((e) => e.origin === "real"), ...built.map((b) => b.manifestEntry)].sort((a, b) =>
    a.path < b.path ? -1 : a.path > b.path ? 1 : 0,
  );
  writeFileSync(MANIFEST, `${JSON.stringify({ version: 1, fixtures }, null, 2)}\n`);
  console.log(`wrote ${built.length} synthetic fixtures and ${MANIFEST}`);
}

if (import.meta.main) main();
