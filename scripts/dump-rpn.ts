// Evidence dump for the formula translator: for every wk1/wks fixture in the manifest,
// print each formula cell's address, cached value and raw RPN bytes in hex. No decoding,
// so the evidence does not depend on the decoder it is used to check.
// Run: bun scripts/dump-rpn.ts [out.md]   (prints to stdout without an argument)
// The "Opcodes seen" section of .kiro/specs/formula-translator/evidence.md is read by hand
// from this output and kept above the generated part.
import { readFileSync, writeFileSync } from "node:fs";
import { a1, cellsInRowMajorOrder, parseWk1 } from "../src/parser/index.ts";

type Entry = { path: string; format: string; origin: string };
const manifest = JSON.parse(readFileSync("fixtures/manifest.json", "utf8")) as { fixtures: Entry[] };

const hex = (b: number) => b.toString(16).padStart(2, "0");
const lines: string[] = ["## Raw formula bytes per fixture", "", "Generated by `bun scripts/dump-rpn.ts`. Bytes are the RPN stream as stored, in hex.", ""];

for (const entry of manifest.fixtures.filter((e) => e.format === "wk1" || e.format === "wks")) {
  const { sheet } = parseWk1(new Uint8Array(readFileSync(entry.path)));
  const formulas = cellsInRowMajorOrder(sheet).filter((c) => c.kind === "formula");
  lines.push(`### ${entry.path} (${entry.origin}, ${formulas.length} formulas)`, "");
  if (formulas.length === 0) {
    lines.push("No formula cells.", "");
    continue;
  }
  lines.push("```");
  for (const c of formulas) {
    if (c.kind !== "formula") continue;
    lines.push(`${a1(c.col, c.row).padEnd(6)} cached=${String(c.cached).padEnd(22)} ${[...c.rpn].map(hex).join(" ")}`);
  }
  lines.push("```", "");
}

const out = process.argv[2];
if (out) writeFileSync(out, lines.join("\n"));
else console.log(lines.join("\n"));
